import os, json
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'file://' + os.path.join(ROOT, 'dist', 'artifact', 'index.html')
OUT = os.path.join(ROOT, 'shots')
BOT = open(os.path.join(os.path.dirname(__file__), 'run.py'), encoding='utf-8').read().split('BOT = r"""')[1].split('"""')[0]
with sync_playwright() as p:
    br = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = br.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    page = ctx.new_page()
    errs = []; page.on('pageerror', lambda e: errs.append(str(e)))
    page.goto(URL); page.wait_for_timeout(1200)
    page.click('text=新的殖民地'); page.wait_for_timeout(300); page.click('#intro .skip'); page.wait_for_timeout(400)
    page.evaluate(BOT); page.evaluate("__bot.resolve(); G.speed=0; __bot.run(11.5); __bot.resolve();")
    before = page.evaluate("({day:G.day,t:G.t,awake:awakeCount(),b:G.buildings.length,res:G.res,tide:G.tide.phase,done:Object.keys(G.story.done).length,rel:Object.keys(G.rel).length, size: JSON.stringify(serialize()).length})")
    page.evaluate("saveGame(true)")
    code = page.evaluate("exportCode()")
    page.reload(); page.wait_for_timeout(1500)
    page.screenshot(path=f'{OUT}/40_title_continue.png')
    page.click('#title .btn.pri'); page.wait_for_timeout(800)
    after = page.evaluate("({day:G.day,t:G.t,awake:awakeCount(),b:G.buildings.length,res:G.res,tide:G.tide.phase,done:Object.keys(G.story.done).length,rel:Object.keys(G.rel).length})")
    page.evaluate(BOT)
    page.evaluate("__bot.run(4); __bot.resolve();")
    cont = page.evaluate("({day:G.day,awake:awakeCount(),act:G.story.act,lost:G.stats.lost})")
    page.screenshot(path=f'{OUT}/41_after_load.png')
    imp = page.evaluate(f"(()=>{{ const o=importCode({json.dumps(code)}); startFromSave(o); return {{day:G.day,awake:awakeCount()}}; }})()")
    print('before', json.dumps(before, ensure_ascii=False))
    print('after ', json.dumps(after, ensure_ascii=False))
    print('cont  ', cont, 'import', imp, 'codeKB', len(code)//1024)
    print('\n'.join(errs[:10]) or 'NO ERRORS')
    br.close()
